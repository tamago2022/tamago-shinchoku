_T.sort(key=lambda x: -len(x[0]))
_OK = re.compile(r'^[a-z\- ]+$')

def romaji_to_kana(s):
    """読めなければ None を返す（推測で埋めない）。"""
    s = s.lower().strip()
    if not _OK.match(s):
        return None
    out = []
    for word in re.split(r'[\- ]+', s):
        if not word: continue
        i = 0; buf = []
        while i < len(word):
            # 促音（同じ子音の重なり）
            if i + 1 < len(word) and word[i] == word[i+1] and word[i] not in "aiueon":
                buf.append("ッ"); i += 1; continue
            for r, k in _T:
                if word.startswith(r, i):
                    buf.append(k); i += len(r); break
            else:
                return None
        out.append("".join(buf))
    return "・".join(out) if len(out) > 1 else out[0]
