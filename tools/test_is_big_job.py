#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""585番：_is_big_job() の再発防止チェック。

背景（467番の依頼から）：
441番「確認待ちに『まとめてOK』を付ける」、452番「『こちらもどうぞ』の暴走を全ページ戻す
＋10件＋高さ揃え」は、どちらも画面の工事・1か所の修正なのに「大きい仕事」と誤判定され、
本体1本のはずが4本・2本に自動分割された（2026-09-06 07:23〜07:52）。

実測で確認した原因：当時の_is_big_job()は指示文の**全文**を見ていた。たまごさんの発言を
そのまま引用すると本文に「全ページ」「10件」のような言葉が混ざり、対象が1つしかない
小さな仕事まで誤検知していた。18:09の修正で「見るのは1行目（題名）だけ」に変わっている
（コミット15273ef）。441・452は共にその修正より前（07:23-07:52）に発車しており、
時系列としても「旧版の誤判定」で説明がつく。

このテストは、その修正が①いまも本当に有効なこと（同じ入力を旧ロジックで再現すると
誤判定するが、今のコードでは誤判定しないこと）と、②これから先も退行しないことの
両方を1本のチェックで担保する。python3 tools/test_is_big_job.py で実行できる。
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import command_ingest as ci  # noqa: E402


def _old_buggy_is_big_job(text):
    """441・452番を誤判定した「旧版」の再現（本文全体を見る／キーワードも当時のまま）。
    2026-09-06のコミットeec2ef8時点のロジックをここに固定でハードコードする
    （ci.BIG_JOB_KEYWORDS等はその後2回修正されて中身が変わっているため、
    比較対象としてここで当時の値を凍結しておく。将来ここを書き換えない）。"""
    old_keywords = ("全ページ", "全件", "すべての", "全部の", "全アーティスト", "全曲", "全記事")
    old_count_re = re.compile(r"(\d{2,})\s*件")
    t = text or ""
    for kw in old_keywords:
        if kw in t:
            return True
    m = old_count_re.search(t)
    if m:
        try:
            if int(m.group(1)) >= 10:
                return True
        except Exception:
            pass
    return False


# ケース1・2：441/452と同じ構造（Dispatchが1行目に短い題名を置き、本文でたまごさんの
# 発言をそのまま引用する。引用部分に「全ページ」「10件」のような言葉が混ざる）。
# 対象は画面の工事1本だけ＝本来は割ってはいけない仕事。
SINGLE_TARGET_CASES = [
    (
        "確認待ちに「まとめてOK」を付ける",
        "確認待ちに「まとめてOK」を付ける\n\n"
        "たまごさんの言葉：「このパチパチパチ、よっぽど楽なんだけど、こんなの1個1個やってらんないよね」\n"
        "→82件を1個ずつ82回押させない。チェックして1回の通信でまとめてqueue_okを流す。",
    ),
    (
        "「こちらもどうぞ」の暴走を全ページ戻す＋10件＋高さ揃え",
        "「こちらもどうぞ」の暴走を全ページ戻す＋10件＋高さ揃え\n\n"
        "たまごさんの言葉：「こちらもどうぞが暴走してて全ページに変なのが出てる。"
        "10件くらいに絞って高さも揃えて」\n→WatchLikeYouMight.tsxの1コンポーネントだけの修正。",
    ),
    (
        # 585番自身の実物（元は467番の一覧作成タスクのwhat本文の一部を再現）。
        # 1行目は"# 元の依頼"で、本文の引用部分に「9本」「82件」「10件ずつ」のような
        # 数字表現が混ざる。対象は index.html 1つの表示ロジックの工事。
        "同じ名前が何本も並ぶのを1行にまとめる",
        "# 元の依頼\n---\n【進捗表・小さい工事】同じ名前が「1/9」「2/9」と並ぶのをやめて、"
        "1行にまとめる。★事情：大きい仕事（例：確認待ち82件の判定）は、3時間で切られて"
        "中途半端に終わるのを防ぐため、機械が10件ずつに割っている。\n---\n"
        "index.htmlの表示だけを直す1本の工事。",
    ),
]

# ケース3：本物の大きい仕事（1行目＝題名そのものに「全件」「82件」のような言葉がある）。
# これは今も大きい仕事として割ってよい（誤って直さないための対照群）。
BIG_JOB_CASES = [
    ("全ページのタイトルを直す", "全ページのタイトルを直す\n\n対象は300ページ以上ある。"),
    ("確認待ち82件を判定する", "確認待ち82件を判定する\n\n1件ずつ実画面を見て良否を決める。"),
    ("すべての棚のサムネイルを揃える", "すべての棚のサムネイルを揃える\n\n棚は50個以上ある。"),
]


def run():
    failures = []

    # ① 旧版（本文全体を見る）なら誤判定していたことを確認する＝この修正の必要性の証拠
    for title, body in SINGLE_TARGET_CASES:
        if not _old_buggy_is_big_job(body):
            failures.append(
                "前提が崩れています：旧版ロジックでも %r が大きい仕事と判定されませんでした"
                "（このケースは『旧版が誤判定していた』ことの証拠にならない）" % title
            )

    # ② 今のコード（1行目だけを見る）では、画面の工事・1か所の修正が誤って
    #    大きい仕事と判定されないこと（441・452の再発防止本体）
    for title, body in SINGLE_TARGET_CASES:
        got = ci._is_big_job(body)
        if got:
            failures.append(
                "回帰：画面の工事・1か所の修正 %r が大きい仕事と誤判定されました"
                "（441番・452番と同じ事故）" % title
            )

    # ③ 本物の大きい仕事は、今のコードでも変わらず大きい仕事として拾えること
    #    （①②の対策でカバレッジが落ちていないことの対照群）
    for title, body in BIG_JOB_CASES:
        got = ci._is_big_job(body)
        if not got:
            failures.append(
                "対照群が崩れています：本物の大きい仕事 %r が大きい仕事と判定されませんでした"
                % title
            )

    if failures:
        print("FAIL（%d件）" % len(failures))
        for f in failures:
            print(" - " + f)
        return 1
    print("PASS：_is_big_job()は441番・452番のような画面の工事・1か所の修正を大きい仕事と"
          "誤判定せず、本物の大きい仕事（全ページ・◯◯件〜）は変わらず拾えています（%d+%dケース確認）"
          % (len(SINGLE_TARGET_CASES), len(BIG_JOB_CASES)))
    return 0


if __name__ == "__main__":
    sys.exit(run())
