def tail_section(path, header, limit=1400):
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except Exception:
        return ""
    idx = text.find(header)
    if idx < 0:
        return ""
    return text[idx:idx + limit]


def live_state():
    out = []
    queue = os.path.join(RULES, "作業キュー.md")

    fire = tail_section(queue, "## 🔥 いま火にかけているもの", 900)
    if fire:
        out.append(fire.strip())

    try:
        with open(queue, encoding="utf-8") as f:
            rows = [ln.rstrip() for ln in f
                    if ln.startswith("|") and re.search(r"🔴|🟠|🟡", ln)]
        if rows:
            out.append("## 受付台帳の未完了（🔴未着手 🟠着手中 🟡未検証）\n" + "\n".join(rows[:40]))
    except Exception:
        pass

    try:
        handoffs = sorted(fn for fn in os.listdir(RULES)
                          if fn.startswith("引き継ぎ_") and fn.endswith(".md"))
        if handoffs:
            out.append("## 最新の引き継ぎ\n必要なら AI出力/_ルール/%s を読む。" % handoffs[-1])
    except Exception:
        pass

    return "\n\n".join(out)


